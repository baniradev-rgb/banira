#!/usr/bin/env python3
"""Banira opportunity scoring model.

Score = sum(weight_i * rating_i) / 5   -> 0..100
Ratings are 1-5 analyst judgements (5 = best for Banira; for risk_safety 5 = safest).
Also runs a Monte Carlo sensitivity test: each weight is randomly scaled by
0.5x-1.5x (then renormalised) 10,000 times and we count how often each option ranks #1.

Usage: python3 score.py [--csv scoring_model.csv] [--out results.md]
"""
import argparse, csv, random, sys
from pathlib import Path

WEIGHTS = {  # must sum to 100
    "demand": 18,          # evidence that customers have the problem and pay to solve it
    "route": 15,           # credible route to first customer without paid ads
    "zero_cost": 12,       # can start and deliver with $0 extra spend
    "differentiation": 12, # manageable competition / clear differentiator
    "price_margin": 10,    # achievable price and gross margin
    "automation": 10,      # share of delivery that can be automated / low manual work
    "recurring": 8,        # recurring-revenue potential
    "scalability": 5,      # can grow beyond one person's hours
    "time_to_revenue": 5,  # speed to first payment
    "risk_safety": 5,      # legal / operational / reputational safety
}
assert sum(WEIGHTS.values()) == 100


def load(path):
    rows = list(csv.DictReader(open(path, newline="", encoding="utf-8")))
    for r in rows:
        for k in WEIGHTS:
            v = int(r[k])
            if not 1 <= v <= 5:
                sys.exit(f"Rating out of range: {r['opportunity']} {k}={v}")
            r[k] = v
    return rows


def score(r, w):
    total = sum(w.values())
    return sum(w[k] * r[k] for k in w) / 5 * (100 / total)


def monte_carlo(rows, n=10_000, seed=42):
    rng = random.Random(seed)
    wins = {r["opportunity"]: 0 for r in rows}
    for _ in range(n):
        w = {k: v * rng.uniform(0.5, 1.5) for k, v in WEIGHTS.items()}
        best = max(rows, key=lambda r: score(r, w))
        wins[best["opportunity"]] += 1
    return {k: v / n for k, v in wins.items() if v}


def scenarios(rows):
    alt = {
        "Base weights": WEIGHTS,
        "Revenue-first (price_margin 20, demand 22)": {**WEIGHTS, "price_margin": 20, "demand": 22},
        "Safety-first (risk_safety 15)": {**WEIGHTS, "risk_safety": 15},
        "Leader's route rating cut by 1": None,  # handled below
    }
    out = []
    for name, w in alt.items():
        rs = [dict(r) for r in rows]
        if w is None:
            w = WEIGHTS
            leader = max(rs, key=lambda r: score(r, WEIGHTS))
            leader["route"] = max(1, leader["route"] - 1)
        ranked = sorted(rs, key=lambda r: -score(r, w))[:3]
        out.append((name, [(r["opportunity"], round(score(r, w), 1)) for r in ranked]))
    return out


def main():
    here = Path(__file__).parent
    ap = argparse.ArgumentParser()
    ap.add_argument("--csv", default=here / "automation_services.csv")
    ap.add_argument("--out", default=here / "automation_scoring_results.md")
    a = ap.parse_args()
    rows = load(a.csv)
    ranked = sorted(rows, key=lambda r: -score(r, WEIGHTS))
    mc = monte_carlo(rows)
    lines = ["# Scoring results (generated by score.py — do not edit by hand)", "",
             "Weights: " + ", ".join(f"{k} {v}" for k, v in WEIGHTS.items()), "",
             "| Rank | # | Opportunity | " + " | ".join(WEIGHTS) + " | Score |",
             "|" + "---|" * (len(WEIGHTS) + 4)]
    for i, r in enumerate(ranked, 1):
        lines.append(f"| {i} | {r['id']} | {r['opportunity']} | " +
                     " | ".join(str(r[k]) for k in WEIGHTS) + f" | **{score(r, WEIGHTS):.1f}** |")
    lines += ["", "## Sensitivity: share of 10,000 random weightings (each weight x0.5–1.5) where option ranks #1", ""]
    for k, v in sorted(mc.items(), key=lambda kv: -kv[1]):
        lines.append(f"- {k}: {v:.1%}")
    lines += ["", "## Scenario tests (top 3)", ""]
    for name, top in scenarios(rows):
        lines.append(f"- **{name}:** " + "; ".join(f"{o} ({s})" for o, s in top))
    Path(a.out).write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
