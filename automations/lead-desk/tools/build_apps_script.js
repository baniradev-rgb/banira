#!/usr/bin/env node
/**
 * Assemble a ready-to-paste Apps Script project for one client.
 *   node tools/build_apps_script.js <client-config.json> <out-dir>
 * Produces: Engine.gs (copy of src/engine.js), Config.gs (CLIENT_CONFIG), Code.gs, appsscript.json
 * Refuses to build if the config fails LeadEngine.checkConfig.
 */
const fs = require('fs');
const path = require('path');
const engine = require('../src/engine.js');

function build(configPath, outDir) {
  const config = JSON.parse(fs.readFileSync(configPath, 'utf8'));
  const problems = engine.checkConfig(config);
  if (problems.length) {
    const err = new Error('Config failed validation:\n- ' + problems.join('\n- '));
    err.problems = problems;
    throw err;
  }
  fs.mkdirSync(outDir, { recursive: true });
  const root = path.join(__dirname, '..');
  const src = fs.readFileSync(path.join(root, 'src/engine.js'), 'utf8')
    .replace(/\nif \(typeof module[^\n]*\n?$/, '\n');
  fs.writeFileSync(path.join(outDir, 'Engine.gs'), '// GENERATED from src/engine.js — do not edit here\n' + src);
  const clean = Object.assign({}, config);
  delete clean._note;
  fs.writeFileSync(path.join(outDir, 'Config.gs'),
    '// GENERATED by build_apps_script.js on ' + new Date().toISOString() + '\nvar CLIENT_CONFIG = ' + JSON.stringify(clean, null, 2) + ';\n');
  fs.copyFileSync(path.join(root, 'apps-script/Code.gs'), path.join(outDir, 'Code.gs'));
  fs.writeFileSync(path.join(outDir, 'appsscript.json'), JSON.stringify({
    timeZone: config.business.timezone,
    runtimeVersion: 'V8',
    exceptionLogging: 'STACKDRIVER',
    webapp: { executeAs: 'USER_DEPLOYING', access: 'ANYONE_ANONYMOUS' },
    oauthScopes: [
      'https://www.googleapis.com/auth/spreadsheets',
      'https://mail.google.com/',
      'https://www.googleapis.com/auth/script.send_mail',
      'https://www.googleapis.com/auth/script.scriptapp',
      'https://www.googleapis.com/auth/forms'
    ].concat(config.bot_check === 'turnstile' ? ['https://www.googleapis.com/auth/script.external_request'] : [])
  }, null, 2));
  return ['Engine.gs', 'Config.gs', 'Code.gs', 'appsscript.json'].map(f => path.join(outDir, f));
}

if (require.main === module) {
  const [cfg, out] = process.argv.slice(2);
  if (!cfg || !out) { console.error('usage: build_apps_script.js <config.json> <out-dir>'); process.exit(1); }
  try { console.log('Built:\n' + build(cfg, out).join('\n')); }
  catch (e) { console.error(e.message); process.exit(2); }
}
module.exports = { build };
